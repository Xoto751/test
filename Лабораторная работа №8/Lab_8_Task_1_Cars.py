class Автомобиль:
    """
    Базовый класс для представления автомобиля.

    Атрибуты:
        марка (str): Марка автомобиля.
        модель (str): Модель автомобиля.
        год_выпуска (int): Год выпуска автомобиля.
        пробег (float): Пробег автомобиля в километрах.
    """

    def __init__(self, марка: str, модель: str, год_выпуска: int, пробег: float):
        """
        Конструктор класса Автомобиль.

        :param марка: Марка автомобиля.
        :param модель: Модель автомобиля.
        :param год_выпуска: Год выпуска автомобиля.
        :param пробег: Пробег автомобиля в километрах.
        """
        self.марка = марка
        self.модель = модель
        self.год_выпуска = год_выпуска
        self.пробег = пробег

    def __str__(self) -> str:
        """
        Возвращает строковое представление автомобиля.

        :return: Строка с описанием автомобиля.
        """
        return f"{self.марка} {self.модель} ({self.год_выпуска}), пробег: {self.пробег} км"

    def __repr__(self) -> str:
        """
        Возвращает формальное строковое представление автомобиля.

        :return: Формальное строковое представление.
        """
        return f"Автомобиль(марка={self.марка!r}, модель={self.модель!r}, год_выпуска={self.год_выпуска!r}, пробег={self.пробег!r})"

    def увеличить_пробег(self, расстояние: float) -> None:
        """
        Увеличивает пробег автомобиля на заданное расстояние.

        :param расстояние: Расстояние в километрах, на которое нужно увеличить пробег.
        """
        if расстояние < 0:
            raise ValueError("Расстояние не может быть отрицательным.")
        self.пробег += расстояние


